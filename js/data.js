/* 状態(%)に追従する説明文。古い設備は修理すると descFix に切り替わり、
   新品でもヘタってくると一言添える（「直したのに文言が壊れたまま」の違和感を消す） */
function equipDesc(def, cond) {
  const base = def.desc || '';
  if (cond == null) return base;
  if (def.old) return cond >= 50 ? (def.descFix || base) : base;
  if (cond < 30) return base + '（かなりヘタってきた。じきに壊れる）';
  if (cond < 60) return base + '（そろそろガタが来ている）';
  return base;
}

