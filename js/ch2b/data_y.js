/* ============ 断面図の枡目を組み立てる ============
   ビルを横から見た絵にする（CHAPTER2_B.md §4-2）。
     ・左の3列 … 各フロア（上にある階ほど上の行）
     ・右の1列 … エレベーターのシャフト（全行ぶち抜き）
   増築して階が増えたら、行数を増やしてもう一度これを呼ぶ＝絵が上に伸びる  */
function buildFloorsY(n) {
  const list = AREAS_Y.slice(0, Math.max(Y_START_AREAS, n | 0));
  const floors = list.filter(a => a.lvl > 0);
  const rows = floors.length;
  for (const a of floors) {
    // lvl が大きい（上の階）ほど、外観では上の段に来る
    a.gy = rows - 1 - floors.filter(b => b.lvl < a.lvl).length;
    a.gx = 0; a.gw = 4; a.gh = 1;
  }
  return { list, rows };
}


